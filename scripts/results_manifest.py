def build_manifest():
    entries = n2_entries() + n3_entries() + jev_entries()
    entries.sort(key=lambda e: e["id"])
    return {"note": NOTE, "results": entries}


def write_manifest():
    manifest = build_manifest()
    MANIFEST_PATH.write_text(json.dumps(manifest, indent=2, sort_keys=False) + "\n")
    print(f"wrote {len(manifest['results'])} entries to {MANIFEST_PATH.relative_to(REPO_ROOT)}")


def check_manifest():
    if not MANIFEST_PATH.exists():
        print(f"MISSING: {MANIFEST_PATH} does not exist; run --write first", file=sys.stderr)
        return 1

    on_disk = json.loads(MANIFEST_PATH.read_text())
    on_disk_by_id = {e["id"]: e for e in on_disk.get("results", [])}

    fresh = build_manifest()
    fresh_by_id = {e["id"]: e for e in fresh["results"]}

    mismatches = []

    if on_disk.get("note") != fresh["note"]:
        mismatches.append("note: manifest 'note' field differs from expected text")

    for id_, fresh_e in fresh_by_id.items():
        disk_e = on_disk_by_id.get(id_)
        if disk_e is None:
            mismatches.append(f"{id_}: missing from manifest on disk (run --write)")
            continue
        if disk_e.get("value") != fresh_e["value"]:
            mismatches.append(
                f"{id_}: value mismatch -- manifest={disk_e.get('value')!r} "
                f"recomputed={fresh_e['value']!r}"
            )
        if disk_e.get("sha256") != fresh_e["sha256"]:
            mismatches.append(
                f"{id_}: sha256 mismatch -- manifest={disk_e.get('sha256')} "
                f"recomputed={fresh_e['sha256']} (artefact changed?)"
            )

    for id_ in on_disk_by_id:
        if id_ not in fresh_by_id:
            mismatches.append(f"{id_}: present in manifest but no longer produced by the script")

    if mismatches:
        print(f"FAIL: {len(mismatches)} mismatch(es)")
        for m in mismatches:
            print(f"  - {m}")
        return 1

    print(f"OK: {len(fresh_by_id)} entries match their artefacts")
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--write", action="store_true", help="(re)generate research/results_manifest.json")
    group.add_argument("--check", action="store_true", help="recompute from artefacts and diff against the manifest on disk")
    args = parser.parse_args()

    if args.write:
        write_manifest()
        return 0
    return check_manifest()


if __name__ == "__main__":
    sys.exit(main())
