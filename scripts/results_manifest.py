def n2_entries():
    entries = []
    all_ledgers = []
    for domain, run_dir in N2_RUNS.items():
        sidecar = f"{run_dir}/sidecar.json"
        ledger = f"{run_dir}/ledger.json"
        all_ledgers.append(ledger)
        stats = load_json(sidecar)["stats"]

        entries.append(entry(
            f"n2_live_{domain}_n_sources_fetched", stats["n_sources_fetched"],
            sidecar, "stats.n_sources_fetched",
        ))
        entries.append(entry(
            f"n2_live_{domain}_n_extracted", stats["n_extracted"],
            sidecar, "stats.n_extracted",
        ))
        entries.append(entry(
            f"n2_live_{domain}_n_located", stats["n_located"],
            sidecar, "stats.n_located (claims with >=1 span)",
        ))
        entries.append(entry(
            f"n2_live_{domain}_evidence_items", sum_evidence_items(ledger),
            ledger, "sum(len(claim.evidence) for claim in claims)",
        ))
        entries.append(entry(
            f"n2_live_{domain}_n_supports", stats["n_supports"],
            sidecar, "stats.n_supports",
        ))
        entries.append(entry(
            f"n2_live_{domain}_n_unknown", stats["n_unknown"],
            sidecar, "stats.n_unknown",
        ))
        entries.append(entry(
            f"n2_live_{domain}_total_cost_usd", stats["total_cost_usd"],
            sidecar, "stats.total_cost_usd",
        ))
        entries.append(entry(
            f"n2_live_{domain}_synthetic_extrapolation",
            stats["label_counts"]["synthetic_extrapolation"],
            sidecar, "stats.label_counts.synthetic_extrapolation",
        ))
        if domain in ("plc", "gdpr_v1"):
            entries.append(entry(
                f"n2_live_{domain}_decoy_false_accepts", decoy_counts(sidecar),
                sidecar, "count of decoys[] where false_accept == true, out of len(decoys)",
            ))

    total_evidence = sum(sum_evidence_items(p) for p in all_ledgers)
    entries.append(entry(
        "n2_live_total_evidence_items", total_evidence,
        sorted(all_ledgers),
        "sum over the three E-LIVE runs of sum(len(claim.evidence) for claim in claims)",
    ))
    return entries


