def n3_entries():
    entries = []
    for domain in N3_DOMAINS:
        path = f"research/n3/{domain}/gapmap.json"
        data = load_json(path)
        checks = data["checks"]

        mec = checks["mismatched_evidence_control"]["total"]
        entries.append(entry(
            f"n3_{domain}_mismatched_evidence_control_total",
            {k: mec[k] for k in ("own_rate", "control_rate", "other_source_only_rate", "n")},
            path, "checks.mismatched_evidence_control.total",
        ))

        ldn = checks["lexical_donor_null"]["total"]
        entries.append(entry(
            f"n3_{domain}_lexical_donor_null_total",
            {k: ldn[k] for k in ("observed", "null_mean", "null_lo", "null_hi")},
            path, "checks.lexical_donor_null.total",
        ))

        ar = checks["anti_renaming"]
        entries.append(entry(
            f"n3_{domain}_anti_renaming",
            {k: ar[k] for k in ("spearman", "j10_high", "j10_low")},
            path, "checks.anti_renaming.{spearman,j10_high,j10_low}",
        ))

        entries.append(entry(
            f"n3_{domain}_promo_excluded", checks["promo_excluded"],
            path, "checks.promo_excluded",
        ))

        entries.append(entry(
            f"n3_{domain}_map_records_count", len(data["map"]),
            path, "len(map)",
        ))

        entries.append(entry(
            f"n3_{domain}_retrieval_gaps_count", len(data["retrieval_gaps"]),
            path, "len(retrieval_gaps)",
        ))
    return entries


