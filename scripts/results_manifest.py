#!/usr/bin/env python3
"""Canonical headline-number manifest for the reports.

Builds/checks research/results_manifest.json: one machine-readable list of
the headline PoC numbers the Main Research Report and Extended Technical
Report use. Every value is read from its source artefact -- never
hard-coded -- so a report claim can be traced to the file and JSON field
that produced it, and re-verified with a hash of that file.

    python3 scripts/results_manifest.py --write   # (re)generate the manifest
    python3 scripts/results_manifest.py --check    # recompute and diff

stdlib only. No network, no model calls.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
MANIFEST_PATH = REPO_ROOT / "research" / "results_manifest.json"

NOTE = (
    "Canonical headline numbers for the Main Research Report and Extended "
    "Technical Report. Generated by scripts/results_manifest.py; check with --check."
)

N2_RUNS = {
    "plc": "reconstruct/runs/20260928T133336Z-59ec876b3d7e",
    "gdpr_v1": "reconstruct/runs/20260928T135354Z-eb840a85b7d1",
    "gdpr_v2": "reconstruct/runs/20260928T145943Z-bc1cc9a30a02",
}
N3_DOMAINS = ["plc", "gdpr_v1", "gdpr_v2"]
JEV_DIR = "research/spikes/jev"

_bytes_cache: dict = {}
_json_cache: dict = {}


def _read_bytes(relpath: str) -> bytes:
    if relpath not in _bytes_cache:
        _bytes_cache[relpath] = (REPO_ROOT / relpath).read_bytes()
    return _bytes_cache[relpath]


def sha256_file(relpath: str) -> str:
    return hashlib.sha256(_read_bytes(relpath)).hexdigest()


def load_json(relpath: str):
    if relpath not in _json_cache:
        _json_cache[relpath] = json.loads(_read_bytes(relpath).decode("utf-8"))
    return _json_cache[relpath]


def combined_hash_of_files(relpaths) -> str:
    """sha256 over the sorted list of each file's own sha256."""
    hashes = sorted(sha256_file(p) for p in relpaths)
    return hashlib.sha256("".join(hashes).encode("utf-8")).hexdigest()


def hash_directory(relpath: str):
    """(file_count, combined sha256 over the sorted per-file hashes) for a directory."""
    d = REPO_ROOT / relpath
    files = sorted(p for p in d.iterdir() if p.is_file())
    rels = [str(p.relative_to(REPO_ROOT)) for p in files]
    return len(files), combined_hash_of_files(rels)


def entry(id_, value, artefact, field):
    if isinstance(artefact, list):
        artefact_sha256 = combined_hash_of_files(artefact)
    elif (REPO_ROOT / artefact).is_dir():
        _, artefact_sha256 = hash_directory(artefact)
    else:
        artefact_sha256 = sha256_file(artefact)
    return {
        "id": id_,
        "value": value,
        "artefact": artefact,
        "field": field,
        "sha256": artefact_sha256,
    }


def sum_evidence_items(ledger_relpath: str) -> int:
    claims = load_json(ledger_relpath)["claims"]
    return sum(len(c.get("evidence", [])) for c in claims)


def decoy_counts(sidecar_relpath: str):
    decoys = load_json(sidecar_relpath)["decoys"]
    n_false_accept = sum(1 for d in decoys if d.get("false_accept"))
    return {"false_accepts": n_false_accept, "total": len(decoys)}


